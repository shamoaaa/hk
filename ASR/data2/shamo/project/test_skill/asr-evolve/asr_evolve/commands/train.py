# -*- coding: utf-8 -*-
"""train 命令 — 远程训练提交/检查/停止.

三个子命令：
  asr-evolve train submit   提交训练（nohup 后台）
  asr-evolve train check    检查训练状态
  asr-evolve train stop     停止训练
"""
from __future__ import annotations

import json
import time
from datetime import datetime
from pathlib import Path

import yaml

from asr_evolve.environment.remote import RemoteExecutor, RemoteConfig


# ---------------------------------------------------------------------------
# 配置加载
# ---------------------------------------------------------------------------

def _load_configs() -> tuple[dict, dict, dict]:
    """加载 remote.yaml, training.yaml, model.yaml，返回 (remote, training, model)。"""
    with open("configs/remote.yaml", encoding="utf-8") as f:
        remote = yaml.safe_load(f)
    with open("configs/training.yaml", encoding="utf-8") as f:
        training = yaml.safe_load(f)
    with open("configs/model.yaml", encoding="utf-8") as f:
        model = yaml.safe_load(f) or {}
    return remote, training, model


def _get_executor(remote_cfg: dict) -> RemoteExecutor:
    """创建并连接 RemoteExecutor。"""
    r = remote_cfg["remote"]
    e = RemoteExecutor(RemoteConfig(
        host=r["host"], port=r["port"],
        username=r["username"], password=r.get("password", ""),
        key_file=r.get("key_file", ""),
        workspace=r["workspace"],
    ))
    e.connect()
    return e


# ---------------------------------------------------------------------------
# 远程脚本生成
# ---------------------------------------------------------------------------

def _build_train_script(
    remote_cfg: dict,
    training_cfg: dict,
    model_cfg: dict,
    output_dir: str,
) -> str:
    """生成远程端的 bash 训练脚本内容。"""
    r = remote_cfg["remote"]
    t = remote_cfg.get("training", {})
    tcfg = training_cfg["training"]
    mcfg = model_cfg.get("model", {})

    ws = r["workspace"]
    funasr_path = t.get("funasr_path", f"{ws}/FunASR")
    model_dir = t.get("model_dir", mcfg.get("model_dir", ""))
    gpus = tcfg["distributed"]["cuda_visible_devices"]
    seaco_id = mcfg.get("seaco", {}).get("seaco_id", 8377)

    # 数据路径（远程）
    train_jsonl = f"{ws}/data/merged/train/train.jsonl"
    dev_jsonl = f"{ws}/data/merged/dev/dev.jsonl"

    script = f"""#!/bin/bash
# Auto-generated by asr-evolve train submit
set -e

export PYTHONPATH={funasr_path}:$PYTHONPATH
export CUDA_VISIBLE_DEVICES={gpus}
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True

cd {ws}
mkdir -p {output_dir}

python3 -m funasr.bin.train \\
  ++model={model_dir} \\
  ++train_data_set_list={train_jsonl} \\
  ++valid_data_set_list={dev_jsonl} \\
  ++dataset_conf.batch_size={tcfg['batch_size']} \\
  ++dataset_conf.batch_type={tcfg['batch_type']} \\
  ++dataset_conf.max_token_length={tcfg['max_token_length']} \\
  ++dataset_conf.num_workers={tcfg['dataloader']['num_workers']} \\
  ++dataset_conf.seaco_id={seaco_id} \\
  ++train_conf.accum_grad={tcfg.get('accum_grad', 1)} \\
  ++train_conf.max_epoch={tcfg['max_epoch']} \\
  ++train_conf.validate_interval={tcfg['validate_interval']} \\
  ++train_conf.save_checkpoint_interval={tcfg['save_checkpoint_interval']} \\
  ++train_conf.keep_nbest_models={tcfg['keep_nbest_models']} \\
  ++train_conf.avg_nbest_model={tcfg['avg_nbest_model']} \\
  ++train_conf.find_unused_parameters=true \\
  ++train_conf.log_interval=20 \\
  '++freeze_param=["hotword_output_layer","seaco_decoder"]' \\
  ++optim_conf.lr={tcfg['learning_rate']} \\
  ++scheduler_conf.warmup_steps={tcfg['warmup_steps']} \\
  ++output_dir={output_dir}
"""
    return script


# ---------------------------------------------------------------------------
# 状态持久化
# ---------------------------------------------------------------------------

_STATE_FILE = Path("logs/train_state.json")


def _save_state(state: dict) -> None:
    """保存训练状态到本地。"""
    _STATE_FILE.parent.mkdir(exist_ok=True)
    _STATE_FILE.write_text(json.dumps(state, indent=2, ensure_ascii=False), encoding="utf-8")


def _load_state() -> dict | None:
    """加载训练状态。"""
    if not _STATE_FILE.exists():
        return None
    try:
        return json.loads(_STATE_FILE.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None


