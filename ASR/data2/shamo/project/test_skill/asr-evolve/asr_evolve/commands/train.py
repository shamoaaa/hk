# 子命令实现
# ---------------------------------------------------------------------------

def cmd_train_submit(args) -> None:
    """提交训练到远程 GPU（nohup 后台模式）。

    支持两种模式:
    - full: 完整训练（使用 training.yaml 中的 max_epoch）
    - probe: 快速验证（2 epoch），用于判断方向是否值得全量训练
    """
    remote_cfg, training_cfg, model_cfg = _load_configs()
    tcfg = training_cfg["training"]
    r = remote_cfg["remote"]
    ws = r["workspace"]

    # Probe mode: override epoch settings (#3)
    train_mode = getattr(args, "mode", "full") or "full"
    if train_mode == "probe":
        probe_cfg = training_cfg.get("probe", {})
        probe_epochs = probe_cfg.get("max_epoch", 2)
        tcfg = dict(tcfg)  # shallow copy to avoid mutating
        tcfg["max_epoch"] = probe_epochs
        tcfg["save_checkpoint_interval"] = 9999  # save only at end
        tcfg["validate_interval"] = 9999  # validate only at end
        print(f"🔍 PROBE 模式: max_epoch={probe_epochs} (快速验证)")

    # 生成 tag
    tag = args.tag if args.tag else f"baseline_{int(time.time())}"
    if train_mode == "probe":
        tag = f"probe_{tag}" if not tag.startswith("probe_") else tag
    output_dir = f"{ws}/output/{tag}"

    # 构建远程脚本
    script_content = _build_train_script(remote_cfg, training_cfg, model_cfg, output_dir)

    # 连接远程
    executor = _get_executor(remote_cfg)

    try:
        # 1. 写远程训练脚本
        remote_script = f"{ws}/run_train_current.sh"
        write_cmd = f"cat > {remote_script} << 'ASR_EVOLVE_EOF'\n{script_content}\nASR_EVOLVE_EOF\nchmod +x {remote_script}"
        rc, _, err = executor.run_command(write_cmd, timeout=10)
        if rc != 0:
            print(f"ERROR: 写入远程脚本失败: {err.strip()}")
            return

        # 2. 创建输出目录
        rc, _, err = executor.run_command(f"mkdir -p {output_dir}", timeout=10)
        if rc != 0:
            print(f"ERROR: 创建输出目录失败: {err.strip()}")
            return

        # 3. nohup 后台启动
        submit_cmd = (
            f"nohup bash {remote_script} > {output_dir}/train_stdout.log 2>&1 & echo $!"
        )
        rc, out, err = executor.run_command(submit_cmd, timeout=15)
        pid = out.strip()

        if rc != 0 or not pid:
            print(f"ERROR: 提交失败 rc={rc}, err={err.strip()}")
            return

        # 4. 保存状态
        state = {
            "tag": tag,
            "pid": pid,
            "output_dir": output_dir,
            "gpu": tcfg["distributed"]["cuda_visible_devices"],
            "submitted_at": datetime.now().isoformat(),
            "mode": train_mode,  # "probe" or "full"
            "config_snapshot": {
                "batch_size": tcfg["batch_size"],
                "batch_type": tcfg["batch_type"],
                "accum_grad": tcfg.get("accum_grad", 1),
                "max_epoch": tcfg["max_epoch"],
                "lr": tcfg["learning_rate"],
                "warmup_steps": tcfg["warmup_steps"],
            },
            "status": "running",
        }
        _save_state(state)

        print(f"TRAIN_SUBMITTED")
        print(f"  tag: {tag}")
        print(f"  pid: {pid}")
        print(f"  GPU: {tcfg['distributed']['cuda_visible_devices']}")
        print(f"  output: {output_dir}")
        print(f"  batch: {tcfg['batch_size']} ({tcfg['batch_type']}), accum_grad={tcfg.get('accum_grad',1)}")
        print(f"  epochs: {tcfg['max_epoch']}")

    finally:
        executor.disconnect()


def cmd_train_check(args) -> None:
    """检查训练状态（进程/GPU/日志/检查点）。"""
    state = _load_state()
    if not state:
        print("No active training. Use 'asr-evolve train submit' first.")
        return

    remote_cfg, _, _ = _load_configs()
    executor = _get_executor(remote_cfg)

    pid = state["pid"]
    output_dir = state["output_dir"]
    gpu_idx = state.get("gpu", "2")

    try:
        # 进程状态
        rc, alive, _ = executor.run_command(
            f"kill -0 {pid} 2>/dev/null && echo RUNNING || echo DONE", timeout=10
        )
        status = alive.strip()

        # GPU
        rc, gpu, _ = executor.run_command(
            f"nvidia-smi -i {gpu_idx} --query-gpu=memory.used,utilization.gpu --format=csv,noheader",
            timeout=10,
        )

        # 日志尾部
        rc, tail, _ = executor.run_command(
            f"tail -3 {output_dir}/train_stdout.log 2>/dev/null", timeout=10
        )

        # 检查点数
        rc, pts, _ = executor.run_command(
            f"find {output_dir} -name '*.pt' 2>/dev/null | wc -l", timeout=10
        )

        print(f"TAG: {state['tag']}")
        print(f"PID: {pid} | Status: {status}")
        print(f"GPU {gpu_idx}: {gpu.strip()}")
        print(f"Checkpoints: {pts.strip()}")
        print(f"Submitted: {state.get('submitted_at', '?')}")
        if tail.strip():
            # 只取最后一行的关键信息
            last = tail.strip().split("\n")[-1]
            print(f"Progress: {last[:120]}")

        # 更新本地状态
        if status == "DONE":
            n_pts = int(pts.strip()) if pts.strip().isdigit() else 0
            state["status"] = "completed" if n_pts > 0 else "failed"
            state["checkpoints"] = n_pts
            state["finished_at"] = datetime.now().isoformat()
            _save_state(state)
            if n_pts > 0:
                mode = state.get("mode", "full")
                if mode == "probe":
                    print(f"\nPROBE_COMPLETED: {n_pts} checkpoints")
                    print("  下一步: 检查 loss 趋势判断是否值得全量训练")
                    print("  通过 → asr-evolve train submit --mode full")
                    print("  失败 → 剪枝此方向")
                else:
                    print(f"\nTRAIN_COMPLETED: {n_pts} checkpoints")
            else:
                print(f"\nTRAIN_FAILED: no checkpoints (silent crash)")

    finally:
        executor.disconnect()


def cmd_train_stop(args) -> None:
    """停止远程训练进程（kill 整个进程树）。"""
    state = _load_state()
    if not state:
        print("No active training to stop.")
        return

    remote_cfg, _, _ = _load_configs()
    executor = _get_executor(remote_cfg)
    pid = state["pid"]

    try:
        # kill 整个进程树：先 pkill 子进程，再 kill 父进程
        kill_cmd = (
            f"pkill -P {pid} 2>/dev/null; "  # kill 所有子进程
            f"kill {pid} 2>/dev/null; "       # kill 父进程
            f"sleep 2; "
            f"pkill -P {pid} -9 2>/dev/null; "  # 强制 kill 残留子进程
            f"kill -9 {pid} 2>/dev/null; "      # 强制 kill 父进程
            f"sleep 1; "
            f"kill -0 {pid} 2>/dev/null && echo STILL_RUNNING || echo KILLED"
        )
        rc, out, _ = executor.run_command(kill_cmd, timeout=15)
        result = out.strip().split('\n')[-1]
        print(f"PID {pid}: {result}")

        if "KILLED" in result:
            state["status"] = "stopped"
            state["stopped_at"] = datetime.now().isoformat()
            _save_state(state)
            print("Training stopped successfully.")
        else:
            print("WARNING: Process may still be running. Check with 'asr-evolve gpu'.")
    finally:
        executor.disconnect()


# ---------------------------------------------------------------------------
# Wait（阻塞等待训练完成）
# ---------------------------------------------------------------------------

def cmd_train_wait(args) -> None:
    """阻塞等待训练完成（本地轮询，每 15 秒短连接检查一次）。"""
    state = _load_state()
    if not state:
        print("No active training to wait for.")
        return

    if state.get("status") != "running":
        print(f"Training not running (status={state.get('status')}). Use 'train check'.")
        return

    remote_cfg, _, _ = _load_configs()
    pid = state["pid"]
    output_dir = state["output_dir"]
    tag = state.get("tag", "?")

    print(f"Waiting for PID {pid} (tag: {tag})...")

    max_wait = 1800  # 30 minutes max
    interval = 15    # check every 15 seconds
    elapsed = 0

    while elapsed < max_wait:
        time.sleep(interval)
        elapsed += interval

        # New short SSH connection each check
        executor = _get_executor(remote_cfg)
        try:
            rc, out, _ = executor.run_command(
                f"kill -0 {pid} 2>/dev/null && echo RUNNING || echo DONE",
                timeout=10,
            )
            status = out.strip()

            if status == "DONE":
                # Check checkpoints
                rc, pts, _ = executor.run_command(
                    f"find {output_dir} -name '*.pt' 2>/dev/null | wc -l",
                    timeout=10,
                )
                n_pts = int(pts.strip()) if pts.strip().isdigit() else 0

                state["status"] = "completed" if n_pts > 0 else "failed"
                state["checkpoints"] = n_pts
                state["finished_at"] = datetime.now().isoformat()
                _save_state(state)

                mode = state.get("mode", "full")
                if n_pts > 0:
                    if mode == "probe":
                        print(f"PROBE_COMPLETED: {n_pts} checkpoints ({elapsed}s)")
                    else:
                        print(f"TRAIN_COMPLETED: {n_pts} checkpoints ({elapsed}s)")
                else:
                    print(f"TRAIN_FAILED: no checkpoints ({elapsed}s)")
                return
            else:
                # Still running — print progress dot
                mins = elapsed // 60
                secs = elapsed % 60
                print(f"  ... still running ({mins}m{secs}s elapsed)", end="\r")

        finally:
            executor.disconnect()

    # Timeout
    print(f"\nWait timeout after {max_wait}s. Use 'train check' to inspect.")


# ---------------------------------------------------------------------------
# CLI 分发
# ---------------------------------------------------------------------------

def cmd_train(args) -> None:
    """train 命令路由。"""
    action = getattr(args, "train_action", None)
    if action == "submit":
        cmd_train_submit(args)
    elif action == "check":
        cmd_train_check(args)
    elif action == "stop":
        cmd_train_stop(args)
    elif action == "wait":
        cmd_train_wait(args)
    else:
        print("用法: asr-evolve train {submit|check|stop}")
